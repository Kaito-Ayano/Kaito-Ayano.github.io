// ── 当前语言 ──
let currentLang = localStorage.getItem('lang') || 'zh';

// ── 翻译函数 ──
function t(key) {
  const lang = LANGS[currentLang];
  if (lang && lang[key] !== undefined) return lang[key];
  // fallback到中文
  if (LANGS.zh[key] !== undefined) return LANGS.zh[key];
  return key;
}

// ── 切换语言 ──
function setLang(lang) {
  if (!LANGS[lang]) return;
  currentLang = lang;
  localStorage.setItem('lang', lang);
  applyTranslations();
  // 同步用户偏好到后端
  if (typeof api !== 'undefined' && typeof AUTH !== 'undefined' && AUTH?.isLoggedIn() && !AUTH?.isGuest()) {
    api.put('/api/user/profile', { lang }).catch(() => {});
  }
}

// ── 应用翻译到 DOM ──
function applyTranslations() {
  // data-i18n 属性
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (typeof val === 'string') el.textContent = val;
  });
  // data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const val = t(el.getAttribute('data-i18n-placeholder'));
    if (typeof val === 'string') el.placeholder = val;
  });
  // data-i18n-html（允许innerHTML）
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const val = t(el.getAttribute('data-i18n-html'));
    if (typeof val === 'string') el.innerHTML = val;
  });
  // 语言按钮高亮
  document.querySelectorAll('.lang-btn').forEach(b =>
    b.classList.toggle('active', b.dataset.lang === currentLang)
  );
  // 重新渲染动态页面
  if (typeof renderLibrary   === 'function') renderLibrary();
  if (typeof renderPlanPage  === 'function') renderPlanPage();
  if (typeof renderWeekDots  === 'function') renderWeekDots();
  if (typeof renderChartsPage=== 'function' && document.getElementById('page-charts')?.classList.contains('active')) renderChartsPage();
  if (typeof renderThemeButtons==='function') renderThemeButtons();
  // 更新 AI 状态文字
  if (typeof updateAIStatus  === 'function') updateAIStatus(typeof AI !== 'undefined' && AI.hasKey());
  // 更新 mood tip
  if (typeof appState !== 'undefined' && appState.mood) selectMood(appState.mood, true);
}
